package io.github.aimi.rag.workflow.log;

import io.github.aimi.rag.workflow.core.flow.FlowExecutionListener;
import io.github.aimi.rag.workflow.core.flow.FlowExecutionRepository;
import io.github.aimi.rag.workflow.core.flow.StepExecutionRecord;
import io.github.aimi.rag.workflow.core.flow.StepFailureRecord;
import io.github.aimi.rag.workflow.core.model.FlowContext;
import io.github.aimi.rag.workflow.core.model.FlowContextKeys;
import io.github.aimi.rag.workflow.core.model.StepStatus;
import io.github.aimi.rag.workflow.log.repository.FlowExecutionJpaRepository;

import javax.sql.DataSource;
import java.time.Instant;

/**
 * Listener that persists flow execution state via FlowExecutionRepository.
 * The execution id is generated by {@code Flow.execute()} and stored in the
 * context under {@link FlowContextKeys#EXECUTION_ID}; this listener only
 * persists it, without generating it.
 *
 * <p>Construct this listener manually and register it via
 * {@code flow.addListener(new PersistentExecutionListener(repository))}.
 */
public class PersistentExecutionListener implements FlowExecutionListener {

    /** Context key prefix for per-step start timestamps. */
    private static final String STEP_START_KEY_PREFIX = "__step_start:";

    private final FlowExecutionRepository repository;
    private final String flowName;

    public PersistentExecutionListener(FlowExecutionRepository repository) {
        this(repository, "unnamed-flow");
    }

    public PersistentExecutionListener(DataSource dataSource) {
        this(new FlowExecutionJpaRepository(dataSource));
    }

    public PersistentExecutionListener(FlowExecutionRepository repository, String flowName) {
        this.repository = repository;
        this.flowName = flowName;
    }

    @Override
    public void onFlowStart(FlowContext context) {
        repository.createExecution(flowName, context);
    }

    @Override
    public void onStepStart(String stepName, FlowContext context) {
        context.set(STEP_START_KEY_PREFIX + stepName, Instant.now());
    }

    @Override
    public void onStepSuccess(String stepName, StepStatus status, FlowContext context) {
        Instant startTime = context.get(STEP_START_KEY_PREFIX + stepName, Instant.class);
        Instant endTime = Instant.now();

        StepExecutionRecord record = StepExecutionRecord.builder()
                .stepName(stepName)
                .status(status)
                .startTime(startTime)
                .endTime(endTime)
                .build();

        repository.saveStepExecution(context, record);
    }

    @Override
    public void onStepFailure(String stepName, Throwable error, FlowContext context) {
        StepFailureRecord record = StepFailureRecord.builder()
                .stepName(stepName)
                .errorMessage(error.getMessage())
                .errorStack(getStackTrace(error))
                .timestamp(Instant.now())
                .build();

        repository.saveStepFailure(context, record);
    }

    @Override
    public void onFlowComplete(FlowContext context) {
        repository.updateExecutionStatus(context, "COMPLETED");
    }

    @Override
    public void onFlowFailure(Throwable error, FlowContext context) {
        repository.updateExecutionStatus(context, "FAILED");
    }

    private static String getStackTrace(Throwable error) {
        if (error == null) {
            return null;
        }
        java.io.StringWriter sw = new java.io.StringWriter();
        error.printStackTrace(new java.io.PrintWriter(sw));
        return sw.toString();
    }
}
